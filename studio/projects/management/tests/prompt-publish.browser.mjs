// Deployed Studio, real local Management API fixture, disposable prompt storage.
// Start TestPromptPublishBrowserAPI with RUNLOOM_PROMPT_PUBLISH_BROWSER=1.
import assert from 'node:assert/strict';
const base = process.env.RUNLOOM_UI_URL || 'http://localhost:4200';
const backend = process.env.RUNLOOM_PROMPT_API || 'http://127.0.0.1:17291';
for (const url of [base, backend]) assert.ok(['localhost', '127.0.0.1'].includes(new URL(url).hostname));
const { chromium } = await import(process.env.RUNLOOM_PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({headless: true, ...(process.env.RUNLOOM_CHROME ? {executablePath: process.env.RUNLOOM_CHROME} : {})});
try {
  const page = await browser.newPage({viewport: {width: 1440, height: 1050}});
  page.setDefaultTimeout(15000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  let writes = 0;
  await page.route(/\/api\/v1\/studio\/prompts(?:[/?]|$)/, async route => {
    const request = route.request(), url = new URL(request.url());
    if (request.method() === 'POST') writes++;
    const response = await route.fetch({url: backend + url.pathname + url.search, headers: {'Content-Type': 'application/json'}});
    await route.fulfill({response});
  });
  await page.goto(base + '/management/prompts');
  await page.locator('#username').fill('admin@runloom.test');
  await page.locator('#password').fill('RunloomLocal!123');
  await page.locator('#kc-login').click();
  const library = page.locator('runloom-prompt-library');
  await library.getByRole('button', {name: 'New prompt', exact: true}).click();
  const editor = library.getByRole('region', {name: 'Library prompt editor'});
  const id = editor.getByLabel('Prompt ID', {exact: true});
  const name = editor.getByLabel('Prompt name', {exact: true});
  const text = editor.getByLabel('Prompt template', {exact: true});
  const publish = editor.getByRole('button', {name: 'Publish prompt', exact: true});
  await name.fill('Customer Summary');
  const generated = await id.inputValue();
  assert.match(generated, /^customer-summary-[a-f0-9]{8}$/);
  await publish.click();
  await editor.locator('#prompt-text-error').waitFor();
  assert.equal(await text.getAttribute('aria-invalid'), 'true');
  await text.fill('Hello from the prompt library.');
  await editor.getByLabel('Prompt tags', {exact: true}).fill('Support, billing, support');
  await id.fill('');
  await publish.click();
  await editor.locator('#prompt-id-error').waitFor();
  assert.equal(writes, 0, 'Invalid drafts must never send a malformed publish URL');
  await id.fill('custom-summary');
  await name.fill('Renamed summary');
  assert.equal(await id.inputValue(), 'custom-summary', 'Manual IDs must not be overwritten');
  const saved = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname.endsWith('/custom-summary/publish'));
  await publish.click();
  const published = await saved;
  assert.equal(published.status(), 200);
  const first = await published.json();
  assert.equal(first.version, 1);
  assert.deepEqual(first.tags, ['support', 'billing']);
  await editor.getByText('Published v1 · r1', {exact: true}).waitFor();
  assert.ok(await id.isDisabled());
  await text.fill('Hello ${vars.missing}');
  await publish.click();
  await editor.locator('runloom-notice').filter({hasText: 'undeclared prompt variable missing'}).waitFor();
  await text.fill('Updated greeting.');
  await editor.getByLabel('Prompt tags', {exact: true}).fill('onboarding');
  const next = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname.endsWith('/custom-summary/publish'));
  await publish.click();
  assert.equal((await (await next).json()).version, 2);
  await editor.getByText('Published v2 · r2', {exact: true}).waitFor();
  const original = await (await fetch(backend + '/api/v1/studio/prompts/custom-summary?version=1')).json();
  assert.equal(original.template.text, 'Hello from the prompt library.');
  assert.deepEqual(original.tags, ['support', 'billing']);
  await page.reload();
  await library.getByRole('button', {name: 'Renamed summary', exact: true}).click();
  await editor.getByText('Published v2 · r2', {exact: true}).waitFor();
  assert.equal(await editor.getByLabel('Prompt tags', {exact: true}).inputValue(), 'onboarding');
  await editor.getByRole('button', {name: 'Close editor', exact: true}).click();
  await library.getByRole('searchbox', {name: 'Search prompts'}).fill('ONBOARDING');
  assert.equal(await library.locator('tbody tr').count(), 1);
  await library.getByLabel('Filter prompt tag', {exact: true}).selectOption('onboarding');
  assert.equal(await library.locator('tbody tr').count(), 1);
  assert.deepEqual(errors, []);
  console.log('PASS: automatic/manual IDs, local validation, publish v1/v2, visible backend errors, immutable history and reload against real Management handlers.');
} finally {
  await browser.close();
  await fetch(backend + '/done', {method: 'POST'});
}
