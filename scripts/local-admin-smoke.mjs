// Local login verification only. Uses the explicitly public development defaults.
import assert from 'node:assert/strict';
const { chromium } = await import(process.env.RUNLOOM_PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.RUNLOOM_UI_URL || 'http://localhost:14200';
assert(['localhost', '127.0.0.1'].includes(new URL(base).hostname), 'Local test only');
const browser = await chromium.launch({ headless: true, ...(process.env.RUNLOOM_CHROME ? { executablePath: process.env.RUNLOOM_CHROME } : {}) });
try {
  const page = await browser.newPage({viewport:{width:1440,height:1000},colorScheme:process.env.RUNLOOM_COLOR_SCHEME || 'light'});
  const errors = [];
  page.on('pageerror', error => errors.push(error.name));
  await page.goto(base);
  await page.locator('#username').fill('admin@runloom.test');
  await page.locator('#password').fill('RunloomLocal!123');
  const profile = page.waitForResponse(response => new URL(response.url()).pathname === '/api/v1/studio/me' && response.ok());
  await page.locator('#kc-login').click();
  const me = await (await profile).json();
  assert.equal(me.user.email, 'admin@runloom.test');
  const orgs = me.organizations.filter(org => org.name === 'Runloom');
  assert.equal(orgs.length, 1);
  assert.equal(orgs[0].role, 'owner');
  const teams = orgs[0].teams.filter(team => team.name === 'General');
  assert.equal(teams.length, 1);
  assert.equal(teams[0].role, 'admin');
  await page.locator('runloom-studio').waitFor();
  await page.getByRole('button', { name: 'Switch organization or team', exact: true }).click();
  await page.getByRole('combobox', { name: 'Organization', exact: true }).selectOption(orgs[0].id);
  await page.getByRole('combobox', { name: 'Team', exact: true }).selectOption(teams[0].id);
  await page.getByRole('button', { name: 'Teams & members', exact: true }).click();
  await page.getByRole('heading', { name: 'Teams & access', exact: true }).waitFor();
  await page.getByRole('heading', { name: 'General members', exact: true }).waitFor();
  if (process.env.RUNLOOM_SCREENSHOT_PATH) await page.screenshot({path:process.env.RUNLOOM_SCREENSHOT_PATH});
  await page.getByRole('button', { name: 'Organization', exact: true }).click();
  await page.getByRole('heading', { name: 'Organization members', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Service accounts', exact: true }).click();
  await page.getByRole('heading', { name: 'Application access', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Workflow secrets', exact: true }).click();
  await page.getByRole('heading', { name: 'Secret vault', exact: true }).waitFor();
  const analyticsResponse = page.waitForResponse(response => new URL(response.url()).pathname.endsWith('/llm-analytics'));
  await page.getByRole('button', { name: 'Cost analytics', exact: true }).click();
  const analyticsHTTP = await analyticsResponse;
  assert.equal(analyticsHTTP.status(), 200);
  const analytics = await analyticsHTTP.json();
  assert.equal(analytics.currency, 'USD');
  assert.equal(analytics.scope, 'authorized_teams_direct_requests');
  assert.equal(typeof analytics.summary.estimated_usd, 'string');
  const dashboard = page.locator('runloom-cost-analytics');
  await dashboard.locator('.main-kpi').waitFor();
  for (const name of ['1 day','1 week','1 month','MTD','YTD','6 months','1 year']) {
    const response = page.waitForResponse(r => new URL(r.url()).pathname.endsWith('/llm-analytics'));
    await dashboard.getByRole('button', {name, exact:true}).click();
    assert.equal((await response).status(), 200);
    await dashboard.locator('.main-kpi').waitFor();
  }
  if (process.env.RUNLOOM_ANALYTICS_SCREENSHOT) await page.screenshot({path:process.env.RUNLOOM_ANALYTICS_SCREENSHOT});
  const budgetResponse = page.waitForResponse(r => new URL(r.url()).pathname.endsWith('/llm-budget-policies'));
  await page.getByRole('button', {name:'LLM budgets',exact:true}).click();
  const budgetHTTP = await budgetResponse;
  assert.equal(budgetHTTP.status(),200);
  const budgets = await budgetHTTP.json();
  assert.equal(budgets.timezone,'UTC');
  assert.equal(budgets.currency,'USD');
  assert(Array.isArray(budgets.items));
  await page.locator('runloom-budget-policies table').waitFor();
  if (process.env.RUNLOOM_BUDGET_SCREENSHOT) await page.screenshot({path:process.env.RUNLOOM_BUDGET_SCREENSHOT});
  await page.getByRole('button', { name: 'Workflows', exact: true }).click();
  await page.locator('runloom-studio').waitFor();
  await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).click();
  const sidebar = page.locator('.workspace-sidebar');
  await sidebar.waitFor({state:'visible'});
  await sidebar.getByRole('button', {name:'Expand sidebar',exact:true}).waitFor();
  assert.equal(await sidebar.getAttribute('inert'), null);
  assert.equal(Math.round((await sidebar.boundingBox()).width), 64);
  await sidebar.getByRole('button', {name:'Teams & members',exact:true}).hover();
  await page.getByRole('tooltip', {name:'Teams & members',exact:true}).waitFor();
  await sidebar.getByRole('button', {name:'Teams & members',exact:true}).click();
  await sidebar.getByRole('button', {name:'Cost analytics',exact:true}).click();
  await dashboard.locator('.main-kpi').waitFor();
  if (process.env.RUNLOOM_RAIL_SCREENSHOT) await page.screenshot({path:process.env.RUNLOOM_RAIL_SCREENSHOT});
  await page.getByRole('button', { name: 'Expand sidebar', exact: true }).click();
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await page.locator('#username').waitFor();
  await page.locator('#username').fill('member@runloom.test');
  await page.locator('#password').fill('RunloomMember!123');
  const memberProfile = page.waitForResponse(response => new URL(response.url()).pathname === '/api/v1/studio/me' && response.ok());
  await page.locator('#kc-login').click();
  const memberMe = await (await memberProfile).json();
  assert.equal(memberMe.user.email, 'member@runloom.test');
  const memberOrgs = memberMe.organizations.filter(org => org.name === 'Runloom');
  assert.equal(memberOrgs.length, 1);
  assert.equal(memberOrgs[0].id, orgs[0].id);
  assert.equal(memberOrgs[0].role, 'member');
  const memberTeams = memberOrgs[0].teams.filter(team => team.name === 'General');
  assert.equal(memberTeams.length, 1);
  assert.equal(memberTeams[0].id, teams[0].id);
  assert.equal(memberTeams[0].role, 'editor');
  await page.locator('runloom-studio').waitFor();
  await page.getByRole('button', {name:'New workflow',exact:true}).waitFor();
  assert.equal(await sidebar.getByRole('button', {name:'Service accounts',exact:true}).count(), 0);
  assert.equal(await sidebar.getByRole('button', {name:'Workflow secrets',exact:true}).count(), 0);
  await page.getByRole('button', {name:'Sign out',exact:true}).click();
  await page.locator('#username').waitFor();
  assert.deepEqual(errors, []);
  console.log('PASS local admin and member logins, shared Runloom/General memberships, owner/admin and member/editor permissions, teams, organization, service accounts, secrets, live cost analytics with seven periods, monthly project budgets, builder, sidebar collapse and logout');
} catch (error) {
  // Authentication URLs may contain session parameters: never print them.
  console.error('Local admin browser verification failed: ' + error.name);
  process.exitCode = 1;
} finally { await browser.close(); }
